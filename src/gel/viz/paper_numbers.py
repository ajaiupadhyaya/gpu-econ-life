"""Numbers and small tables for the paper, generated from result files (CLAUDE.md rule 3).

Every number quoted in paper/sections/*.tex is a macro defined here, read from a CSV/JSON in
paper/tables or data/processed. Nothing in the prose is typed by hand.

Outputs: paper/numbers.tex, paper/tables/p4_facts.tex, paper/tables/p5_review.tex,
paper/tables/m8_triangulation.tex
Usage: uv run python -m gel.viz.paper_numbers
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

import polars as pl

T = Path("paper/tables")
OUT = Path("paper/numbers.tex")


class Numbers:
    def __init__(self) -> None:
        self.defs: dict[str, str] = {}

    def add(self, name: str, value: float | int | str, fmt: str = ".2f") -> None:
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name}")
        if name in self.defs:
            raise ValueError(f"duplicate macro {name}")
        if isinstance(value, str):
            text = value
        elif fmt == ",":
            text = f"{int(round(value)):,}".replace(",", "{,}")
        elif fmt in ("pct", "pct1"):
            text = num(100 * value, ".0f" if fmt == "pct" else ".1f") + "\\%"
        else:
            text = num(value, fmt) if fmt != "d" else f"{value:d}"
        self.defs[name] = text

    def tex(self) -> str:
        lines = ["% Generated by gel.viz.paper_numbers from paper/tables. Do not edit."]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.defs.items())]
        return "\n".join(lines) + "\n"


def num(x: float, fmt: str = ".2f") -> str:
    """A number for a LaTeX table cell, with a typeset minus sign."""
    t = f"{x:{fmt}}"
    if t.startswith("-") and float(t) == 0:
        t = t[1:]
    return "$-$" + t[1:] if t.startswith("-") else t


def _row(df: pl.DataFrame, **eq) -> dict:
    out = df
    for k, v in eq.items():
        out = out.filter(pl.col(k) == v)
    if out.height != 1:
        raise ValueError(f"expected one row for {eq}, got {out.height}")
    return out.row(0, named=True)


def panel_numbers(n: Numbers) -> None:
    report = Path("docs/cleaning_report.md").read_text()
    m = re.search(r"Input rows: ([\d,]+) historical and ([\d,]+) live, ([\d,]+) in all", report)
    n.add("nRawRows", int(m.group(3).replace(",", "")), ",")
    m = re.search(r"Final panel: ([\d,]+) listing-months, (\S+) to (\S+)\.", report)
    n.add("nPanelRows", int(m.group(1).replace(",", "")), ",")
    panel = pl.read_parquet("data/processed/panel.parquet")
    n.add("nHyperscalerShare", (panel["provider_type"] == "hyperscaler").mean(), "pct")
    n.add("nNeocloudRows", int((panel["provider_type"] == "neocloud").sum()), ",")
    sample = pl.read_csv(T / "p5_sample.csv")
    n.add("nSampleRows", int(sample["listing_months"].sum()), ",")
    rep = pl.read_csv(T / "p5_review_repricing.csv")
    nonspot = rep.filter(pl.col("contract_type") != "spot")
    share = float(
        (nonspot["share_unchanged"] * nonspot["transitions"]).sum() / nonspot["transitions"].sum()
    )
    n.add("nListUnchanged", share, "pct")
    n.add("nListTransitions", int(nonspot["transitions"].sum()), ",")
    spot = rep.filter((pl.col("contract_type") == "spot") & (pl.col("provider") == "aws"))
    n.add("nAwsSpotUnchanged", float(spot["share_unchanged"][0]), "pct")
    v = panel.filter(
        (pl.col("provider") == "aws")
        & (pl.col("chip") == "v100")
        & (pl.col("contract_type") == "on_demand")
    )
    yearly = v.group_by(pl.col("month").dt.year()).agg(pl.col("price_usd_per_gpu_hour").median())
    if yearly["price_usd_per_gpu_hour"].n_unique() == 1:
        n.add("nAwsVHundredPrice", float(yearly["price_usd_per_gpu_hour"][0]), ".2f")
    n.add("nAwsVHundredFirstYear", int(yearly["month"].min()), "d")
    n.add("nAwsVHundredLastYear", int(yearly["month"].max()), "d")
    est = panel.filter(pl.col("chip").is_in(sample["chip"].to_list()))
    goog = est.filter(
        pl.col("price_outlier").not_() & pl.col("price_usd_per_gpu_hour_real2025").is_not_null()
    )
    n.add("nGoogleShare", float((goog["provider"] == "google_cloud").mean()), "pct")
    facts = pl.read_csv(T / "p4_descriptive_facts.csv")
    h = _row(facts, chip="h100_sxm")
    n.add("nHHundredHypNeo", h["median_hyperscaler_over_neocloud"], ".2f")
    n.add("nHHundredDispersion", h["median_max_over_min"], ".2f")


def profile_numbers(n: Numbers) -> None:
    s = pl.read_csv(T / "p5_summary.csv").filter(pl.col("sample") == "all")
    names = {
        "s1a_tflops": "OneA",
        "s1b_three_specs": "OneB",
        "s2_frontier": "Two",
        "s4_shape": "Four",
    }
    meas = {"rate_0_2": "RateEarly", "rate_2_4": "RateLate", "early_minus_late_rate": "Shape"}
    for spec, sp in names.items():
        for m, mm in meas.items():
            hit = s.filter((pl.col("spec") == spec) & (pl.col("measure") == m))
            if hit.is_empty():
                continue
            r = hit.row(0, named=True)
            n.add(f"n{sp}{mm}", r["estimate"])
            n.add(f"n{sp}{mm}Lo", r["wcb_ci_low"])
            n.add(f"n{sp}{mm}Hi", r["wcb_ci_high"])
    r = _row(s, spec="s1a_tflops", measure="coef_ln_tflops")
    n.add("nTflopsCoef", r["estimate"])
    full = pl.read_csv(T / "p5_summary.csv")
    for sample, nm in (("contract:spot", "Spot"), ("contract:on_demand", "OnDemand")):
        r = _row(full, sample=sample, spec="s4_shape", measure="early_minus_late_rate")
        n.add(f"nFourShape{nm}", r["estimate"])
        n.add(f"nFourShape{nm}Lo", r["wcb_ci_low"])
        n.add(f"nFourShape{nm}Hi", r["wcb_ci_high"])
    r = _row(
        full,
        sample="weighted_provider_chip_month",
        spec="s4_shape",
        measure="early_minus_late_rate",
    )
    n.add("nFourShapePcm", r["estimate"])
    wcr = pl.read_csv(T / "p5_review_wcr.csv")
    r = _row(wcr, spec="s4_shape", measure="early_minus_late_rate")
    n.add("nFourShapeWcrP", r["wcr_p"])
    n.add("nFourShapeWcuP", pval(r["wcu_p"], r["p_floor"]))
    r = _row(wcr, spec="s2_frontier", measure="early_minus_late_rate")
    n.add("nTwoShapeWcrP", r["wcr_p"])
    inv = pl.read_csv(T / "p5_review_wcr_interval.csv").row(0, named=True)
    n.add("nFourShapeWcrLo", inv["wcr_ci_low"])
    n.add("nFourShapeWcrHi", inv["wcr_ci_high"])
    mc = pl.read_csv(T / "p5_review_monte_carlo.csv")
    for method, nm in (("wcu", "Wcu"), ("wcr", "Wcr"), ("cr1_chip", "Crchip")):
        cov = mc.filter(pl.col("method") == method)["coverage"]
        n.add(f"nCov{nm}Lo", float(cov.min()), "pct")
        n.add(f"nCov{nm}Hi", float(cov.max()), "pct")
    n.add("nMcReps", int(mc["reps"][0]), "d")
    perm = Path(T / "p5_review_permutation_summary.csv")
    if perm.exists():
        p = pl.read_csv(perm).row(0, named=True)
        n.add("nPermAssignments", int(p["assignments"]), ",")
        n.add("nPermP", p["p_two_sided"], ".4f")
        n.add("nPermSharePositive", p["share_positive"], "pct")
    trends = pl.read_csv(T / "p5_review_chip_trends.csv")
    n.add("nShapeChipTrendZero", float(trends["early_minus_late_rate"][0]))
    rp = pl.read_csv(T / "p5_review_repricing_shape.csv")
    r = _row(rp, check="non-spot listings that change price")
    n.add("nShapeListMovers", r["early_minus_late_rate"])
    n.add("nShapeListMoversSe", r["early_minus_late_rate_se_provider"])
    n.add("nListMoversRows", r["n"], ",")
    w = pl.read_csv(T / "p5_review_weighting.csv")
    r = _row(w, check="providers weighted equally", spec="s4_shape")
    n.add("nShapeEqualProv", r["early_minus_late_rate"])
    r = _row(w, check="without Google", spec="s4_shape")
    n.add("nShapeNoGoogle", r["early_minus_late_rate"])
    loo = pl.read_csv(T / "p5_review_leave_one_out.csv")
    r = _row(loo, check="drop h200", spec="s1a_tflops")
    n.add("nOneARateEarlyNoHTwoHundred", r["rate_0_2"])
    ev = pl.read_csv(T / "p5_event_study.csv")
    r = _row(ev, measure="h2_first_year_after")
    n.add("nHTwo", r["estimate"])
    n.add("nHTwoLo", r["wcb_ci_low"])
    n.add("nHTwoHi", r["wcb_ci_high"])
    r = _row(ev, measure="ev_+6_+11")
    n.add("nEvSixEleven", r["estimate"])
    paths = pl.read_csv(T / "p5_cohort_paths.csv").filter(pl.col("sample") == "all")
    for chip, age, nm in (
        ("v100", 48, "VHundredFour"),
        ("v100", 108, "VHundredNine"),
        ("a100_40gb", 60, "AHundredFive"),
        ("h100_sxm", 12, "HHundredOne"),
        ("h100_sxm", 36, "HHundredThree"),
        ("h100_sxm", 48, "HHundredFour"),
    ):
        r = _row(paths, chip=chip, age_months_from=age)
        n.add(f"nPath{nm}", r["estimate"])
        n.add(f"nPath{nm}Pct", -(math.exp(r["estimate"]) - 1), "pct")


def value_numbers(n: Numbers) -> None:
    s = pl.read_csv(T / "p6_summary.csv")
    b = s.filter((pl.col("case") == "base") & (pl.col("chip") == "h100_sxm"))
    for prof, nm in (
        ("realized_older", "Real"),
        ("s2_frontier", "Two"),
        ("s4_d-0.20", "FourTwenty"),
        ("s4_d-0.40", "FourForty"),
    ):
        r = _row(b, profile=prof)
        n.add(f"nVal{nm}LostThree", r["share_lost_y3"], "pct")
        n.add(f"nVal{nm}LostOne", r["share_lost_y1"], "pct")
        n.add(f"nVal{nm}Sle", r["sl_equivalent_life"], ".1f")
        n.add(f"nVal{nm}VzeroCapex", r["v0_over_capex"], ".1f")
        n.add(f"nVal{nm}RentZero", r["rent_age0"], ".2f")
    r = _row(b, profile="realized_older")
    n.add("nValOpex", r["opex_per_hour"], ".2f")
    n.add("nValRentNow", r["rent_now"], ".2f")
    sens = s.filter(
        (pl.col("case") == "sensitivity")
        & (pl.col("chip") == "h100_sxm")
        & (pl.col("profile") == "realized_older")
    )
    r = _row(sens, horizon=6.0)
    n.add("nValRealSleSix", r["sl_equivalent_life"], ".1f")
    r = _row(sens, horizon=5.0)
    n.add("nValRealSleFive", r["sl_equivalent_life"], ".1f")
    grid = s.filter(
        (pl.col("case") == "grid")
        & (pl.col("chip") == "h100_sxm")
        & (pl.col("profile") == "realized_older")
    )
    n.add("nValRealVzeroLo", float(grid["v0_over_capex"].min()), ".1f")
    n.add("nValRealVzeroHi", float(grid["v0_over_capex"].max()), ".1f")
    n.add("nTstarAll", "never" if s["t_star"].is_infinite().all() else "sometimes")


def triangulation_numbers(n: Numbers) -> None:
    m8 = pl.read_csv(T / "m8_triangulation.csv")
    r = _row(m8, chip="h100_sxm")
    n.add("nPThreeMedian", r["p3_median"], ".1f")
    n.add("nPThreePTen", r["p3_p10"], ".1f")
    n.add("nPThreePNinety", r["p3_p90"], ".1f")
    n.add("nPThreeAbundant", r["p3_abundant_median"], ".1f")
    n.add("nPThreeNoScarcity", r["p3_no_scarcity_median"], ".1f")
    n.add("nPTwoLopexLo", r["p2_Lopex_low"], ".1f")
    n.add("nPTwoLopexHi", r["p2_Lopex_high"], ".1f")
    n.add("nPOneDHHundred", r["p1_D_median"])
    att = pl.read_csv(T / "m8_attribution.csv")
    markup = att.filter(pl.col("quantity").str.contains("(?i)markup share"))
    if markup.height:
        n.add("nMarkupShare", float(markup["value"][0]), "pct")


FIRM_NAMES = {
    "MSFT": "Microsoft",
    "GOOGL": "Alphabet",
    "AMZN": "Amazon",
    "META": "Meta",
    "ORCL": "Oracle",
    "CRWV": "CoreWeave",
    "NBIS": "Nebius",
}
HYPERSCALERS = ["MSFT", "GOOGL", "AMZN", "META", "ORCL"]


def restatement_base() -> pl.DataFrame:
    """Latest fiscal year per firm; server share 0.6, GPU share 0.5, cohorts from 2020,
    disclosed book lives, effective tax rate."""
    d = pl.read_csv(T / "p7_restatement.csv").filter(
        (pl.col("server_share") == 0.6)
        & (pl.col("gpu_share") == 0.5)
        & (pl.col("gpu_cohort_start_fy") == 2020)
        & (pl.col("book_variant") == "disclosed")
        & (pl.col("tax_basis") == "effective")
    )
    last = d.group_by("firm").agg(pl.col("fiscal_year").max().alias("_fy"))
    return d.join(last, on="firm").filter(pl.col("fiscal_year") == pl.col("_fy"))


def accounting_numbers(n: Numbers) -> None:
    if not (T / "p7_restatement.csv").exists():
        return
    b = restatement_base().filter(pl.col("firm").is_in(HYPERSCALERS))
    for sched, nm in (
        ("market_realized_older_h100_sxm", "Real"),
        ("market_s4_d-0.40_h100_sxm", "FourForty"),
        ("sl_4y", "SlFour"),
    ):
        x = b.filter(pl.col("schedule") == sched)
        n.add(f"nAcct{nm}OiPctLo", float(x["delta_oi_pct"].min()) / 100, "pct1")
        n.add(f"nAcct{nm}OiPctHi", float(x["delta_oi_pct"].max()) / 100, "pct1")
        n.add(f"nAcct{nm}OiBnLo", float(x["delta_operating_income_usd"].min()) / 1e9, ".1f")
        n.add(f"nAcct{nm}OiBnHi", float(x["delta_operating_income_usd"].max()) / 1e9, ".1f")
    x = b.filter(pl.col("schedule") == "market_s4_d-0.40_h100_sxm").sort("delta_oi_pct")
    r = x.row(0, named=True)
    n.add("nAcctFourFortyWorstFirm", FIRM_NAMES[r["firm"]])
    n.add("nAcctFourFortyWorstPct", r["delta_oi_pct"] / 100, "pct1")
    n.add("nAcctFourFortyWorstEps", r["delta_eps"], ".2f")
    n.add("nAcctFourFortyWorstFy", int(r["fiscal_year"]), "d")
    msft = b.filter((pl.col("firm") == "MSFT") & (pl.col("schedule") == "sl_4y")).row(0, named=True)
    n.add("nAcctMsftFy", int(msft["fiscal_year"]), "d")
    n.add("nAcctMsftGpuCapexBn", msft["gpu_capex_usd"] / 1e9, ".1f")
    n.add("nAcctMsftCapexBn", msft["capex_usd"] / 1e9, ".1f")


def pval(p: float, floor: float) -> str:
    return f"$<${floor:.4f}" if p < floor else f"{p:.3f}"


def tables() -> None:
    facts = pl.read_csv(T / "p4_descriptive_facts.csv").filter(
        pl.col("chip").is_in(
            ["v100", "a100_40gb", "a100_80gb", "h100_pcie", "h100_sxm", "h200", "b200"]
        )
    )
    label = {
        "v100": "V100",
        "a100_40gb": "A100 40GB",
        "a100_80gb": "A100 80GB",
        "h100_pcie": "H100 PCIe",
        "h100_sxm": "H100 SXM",
        "h200": "H200",
        "b200": "B200",
    }
    lines = [
        "% Generated by gel.viz.paper_numbers from p4_descriptive_facts.csv and p5_sample.csv.",
        "\\begin{tabular}{lrrrrrr}",
        "\\hline",
        "Chip & Listing-months & Providers & First month & Ages (months) & Hyperscaler/neocloud"
        " & Max/min provider \\\\",
        "\\hline",
    ]
    sample = pl.read_csv(T / "p5_sample.csv")
    for chip, lab in label.items():
        f = _row(facts, chip=chip)
        s = _row(sample, chip=chip)
        lines.append(
            f"{lab} & {s['listing_months']:,} & {s['providers']} & {s['first_month'][:7]}"
            f" & {s['min_age_months']}--{s['max_age_months']}"
            f" & {f['median_hyperscaler_over_neocloud']:.2f} & {f['median_max_over_min']:.2f} \\\\"
        )
    lines += ["\\hline", "\\end{tabular}", ""]
    (T / "p4_facts.tex").write_text("\n".join(lines).replace(",", "{,}").replace("{,} ", ", "))

    wcr = pl.read_csv(T / "p5_review_wcr.csv")
    spec_label = {
        "s1a_tflops": "1a quality index",
        "s1b_three_specs": "1b three specs",
        "s2_frontier": "2 frontier-relative",
        "s4_shape": "4 shape only",
    }
    lines = [
        "% Generated by gel.viz.paper_numbers from p5_review_wcr.csv.",
        "\\begin{tabular}{llrrrr}",
        "\\hline",
        "Strategy & Measure & Estimate & SE (CR1, chip) & $p$ (WCU) & $p$ (WCR) \\\\",
        "\\hline",
    ]
    mlabel = {
        "rate_0_2": "rate, yrs 0--2",
        "rate_2_4": "rate, yrs 2--4",
        "early_minus_late_rate": "early $-$ late",
    }
    for r in wcr.iter_rows(named=True):
        if r["measure"] not in mlabel:
            continue
        lines.append(
            f"{spec_label[r['spec']]} & {mlabel[r['measure']]} & {num(r['estimate'])}"
            f" & {num(r['se_cr1_chip'])} & {pval(r['wcu_p'], r['p_floor'])}"
            f" & {pval(r['wcr_p'], r['p_floor'])} \\\\"
        )
    lines += ["\\hline", "\\end{tabular}", ""]
    (T / "p5_review.tex").write_text("\n".join(lines))

    m8 = pl.read_csv(T / "m8_triangulation.csv")
    lines = [
        "% Generated by gel.viz.paper_numbers from m8_triangulation.csv.",
        "\\begin{tabular}{lrrrr}",
        "\\hline",
        "Generation (age, yrs) & P1 discount $D$ & P1 life to opex & P2 life to opex"
        " & P3 retirement age (P10--P90) \\\\",
        "\\hline",
    ]
    for r in m8.iter_rows(named=True):
        lines.append(
            f"{r['generation']} ({r['age_now_y']:.1f}) & {num(r['p1_D_median'])}"
            f" [{num(r['p1_D_low'])}, {num(r['p1_D_high'])}]"
            f" & {r['p1_Lopex_low']:.1f}--{r['p1_Lopex_high']:.1f}"
            f" & {r['p2_Lopex_low']:.1f}--{r['p2_Lopex_high']:.1f}"
            f" & {r['p3_median']:.1f} ({r['p3_p10']:.1f}--{r['p3_p90']:.1f}) \\\\"
        )
    lines += ["\\hline", "\\end{tabular}", ""]
    (T / "m8_triangulation.tex").write_text("\n".join(lines))


def lives_table() -> None:
    """Table of disclosed server useful lives from config/accounting.yaml (quotes and accession
    numbers in docs/useful_lives.md)."""
    import yaml

    cfg = yaml.safe_load(Path("config/accounting.yaml").read_text())
    lines = [
        "% Generated by gel.viz.paper_numbers from config/accounting.yaml (book_life).",
        "\\begin{tabular}{lll}",
        "\\hline",
        "Firm & Fiscal year of effect & Server useful life (years) \\\\",
        "\\hline",
    ]
    for firm, hist in cfg["book_life"].items():
        steps = sorted(hist.items())
        prev = None
        for fy, life in steps:
            if prev is not None:
                lines.append(f"{FIRM_NAMES[firm]} & {fy} & {prev:g} $\\to$ {life:g} \\\\")
            prev = life
    lines += ["\\hline", "\\end{tabular}", ""]
    (T / "p7_useful_lives.tex").write_text("\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    n = Numbers()
    panel_numbers(n)
    profile_numbers(n)
    value_numbers(n)
    triangulation_numbers(n)
    accounting_numbers(n)
    OUT.write_text(n.tex())
    tables()
    if Path("config/accounting.yaml").exists():
        lives_table()
    print(
        f"wrote {OUT} ({len(n.defs)} macros) and paper/tables/p4_facts.tex, p5_review.tex,"
        " m8_triangulation.tex"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
