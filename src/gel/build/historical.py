"""Phase 2 outputs: the coverage report, its heatmap, and the hand-check sample.

uv run python -m gel.build.historical
"""

import glob
import random
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import polars as pl  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
SAMPLE_SIZE = 40
SAMPLE_SEED = 20261031
SURFACE = "#fcfcfb"
CELL = "#256abf"
INK = "#3d3d3a"
SAMPLE_COLUMNS = [
    "provider",
    "retrieved_at",
    "chip",
    "gpu_count",
    "contract_type",
    "term_months",
    "sku",
    "price_usd_per_hour_instance",
    "price_usd_per_gpu_hour",
    "check_url",
    "raw_file",
]


def load_history(root: Path) -> pl.DataFrame:
    paths = [
        *glob.glob(str(root / "data/interim/wayback/listings.parquet")),
        *glob.glob(str(root / "data/interim/aws_history/*.parquet")),
        *glob.glob(str(root / "data/interim/skypilot_history/*/*.parquet")),
    ]
    return pl.concat([pl.read_parquet(p) for p in paths])


def _with_month(frame: pl.DataFrame) -> pl.DataFrame:
    return frame.with_columns(pl.col("retrieved_at").str.slice(0, 7).alias("month"))


def coverage_table(frame: pl.DataFrame) -> pl.DataFrame:
    return (
        _with_month(frame)
        .group_by("provider", "chip")
        .agg(
            pl.col("month").min().alias("first"),
            pl.col("month").max().alias("last"),
            pl.col("month").n_unique().alias("months"),
            pl.len().alias("rows"),
        )
        .sort("provider", "chip")
    )


def _markdown(table: pl.DataFrame) -> str:
    lines = [
        "| " + " | ".join(table.columns) + " |",
        "| " + " | ".join("---" for _ in table.columns) + " |",
    ]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in table.iter_rows()]
    return "\n".join(lines)


def render_report(frame: pl.DataFrame) -> str:
    by_source = frame.group_by("provider", "collector").len("rows").sort("provider", "collector")
    by_contract = frame.group_by("contract_type").len("rows").sort("contract_type")
    return "\n".join(
        [
            "# Historical coverage",
            "",
            f"Generated by `python -m gel.build.historical`: {frame.height} rows of historical prices.",
            "",
            "Each filled cell is a month with at least one price for that provider and chip. A",
            "blank is a gap, because prices are never carried forward. Months are not equally",
            "informative: most on-demand prices barely move.",
            "",
            "![Coverage by chip, provider and month](figures/coverage_heatmap.png)",
            "",
            "## Coverage by provider and chip",
            "",
            _markdown(coverage_table(frame)),
            "",
            "## Rows by provider and source",
            "",
            _markdown(by_source),
            "",
            "## Rows by contract type",
            "",
            _markdown(by_contract),
            "",
        ]
    )


def heatmap(frame: pl.DataFrame, path: Path) -> None:
    data = _with_month(frame).select("provider", "chip", "month").unique()
    months = pl.date_range(
        pl.date(2017, 10, 1), pl.date(2026, 10, 1), "1mo", eager=True
    ).dt.strftime("%Y-%m")
    index = {m: i for i, m in enumerate(months)}
    rows = sorted({(p, c) for p, c in data.select("provider", "chip").iter_rows()})
    position = {r: i for i, r in enumerate(rows)}
    fig, ax = plt.subplots(figsize=(11, 0.24 * len(rows) + 1.2), facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    for provider, chip, month in data.iter_rows():
        ax.barh(position[(provider, chip)], 0.9, left=index[month] + 0.05, height=0.78, color=CELL)
    ax.set_yticks(range(len(rows)), [f"{p}  {c}" for p, c in rows], fontsize=8, color=INK)
    ticks = [i for i, m in enumerate(months) if m.endswith("-01")]
    ax.set_xticks(ticks, [months[i][:4] for i in ticks], fontsize=8, color=INK)
    ax.set_xlim(0, len(months))
    ax.set_ylim(len(rows) - 0.5, -0.5)
    ax.tick_params(length=0)
    for spine in ax.spines.values():
        spine.set_visible(False)
    ax.grid(axis="x", color="#e7e6e2", linewidth=0.6)
    ax.set_axisbelow(True)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=160)
    plt.close(fig)


def validation_sample(frame: pl.DataFrame, n: int, seed: int) -> pl.DataFrame:
    """Rows parsed from archived pages, spread evenly across provider and year."""
    rows = (
        frame.filter(pl.col("collector") == "wayback")
        .with_columns(
            pl.col("retrieved_at").str.slice(0, 4).alias("year"),
            pl.col("source_url").str.replace("id_/", "/", literal=True).alias("check_url"),
        )
        .sort("provider", "retrieved_at", "sku", "contract_type", "price_usd_per_gpu_hour")
    )
    if rows.height < n:
        raise ValueError(f"asked for {n} rows but only {rows.height} exist")
    rng = random.Random(seed)
    strata = {}
    for row in rows.iter_rows(named=True):
        strata.setdefault((row["provider"], row["year"]), []).append(row)
    for members in strata.values():
        rng.shuffle(members)
    order = sorted(strata)
    picked: list[dict] = []
    while len(picked) < n:
        for key in order:
            if strata[key] and len(picked) < n:
                picked.append(strata[key].pop())
    return pl.DataFrame(picked).select(SAMPLE_COLUMNS)


def main(root: Path = ROOT) -> int:
    frame = load_history(root)
    (root / "docs/coverage.md").write_text(render_report(frame))
    heatmap(frame, root / "docs/figures/coverage_heatmap.png")
    sample = validation_sample(frame, SAMPLE_SIZE, SAMPLE_SEED)
    sample.write_csv(root / "data/interim/validation_sample.csv")
    print(frame.height, "rows;", sample.height, "sampled")
    return 0


if __name__ == "__main__":
    sys.exit(main())
